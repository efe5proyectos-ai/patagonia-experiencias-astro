import { initializeTestEnvironment, assertSucceeds, assertFails } from '@firebase/rules-unit-testing';
import fs from 'node:fs';
const env = await initializeTestEnvironment({ projectId:'patagonia-experiencias', storage:{ rules: fs.readFileSync('storage.rules','utf8'), host:'127.0.0.1', port:9199 }});
const img = new Uint8Array([137,80,78,71]);
const anon = env.authenticatedContext('anon1',{firebase:{sign_in_provider:'anonymous'}}).storage();
const real = env.authenticatedContext('uidReal',{firebase:{sign_in_provider:'google.com'}, email:'p@x.com'}).storage();
const nadie = env.unauthenticatedContext().storage();
const put=(s,p,type,data=img)=>s.ref(p).put(data,{contentType:type});
let ok=0,fail=0; const t=async(n,p)=>{try{await p;ok++;console.log('✔',n)}catch(e){fail++;console.log('✘',n,e.message)}};
await env.withSecurityRulesDisabled(async c=>{await c.storage().ref('tours/a.png').put(img,{contentType:'image/png'})});
await t('visitante anónimo NO sube a tours', assertFails(put(anon,'tours/x.png','image/png')));
await t('visitante anónimo NO borra foto de tour', assertFails(anon.ref('tours/a.png').delete()));
await t('sin sesión NO sube', assertFails(put(nadie,'tours/x.png','image/png')));
await t('prestador/admin SÍ sube a tours', assertSucceeds(put(real,'tours/x.png','image/png')));
await t('prestador NO sube SVG', assertFails(put(real,'tours/x.svg','image/svg+xml')));
await t('prestador SÍ sube foto HEIC de iPhone', assertSucceeds(put(real,'agencias/logo.heic','image/heic')));
await t('prestador NO sube PDF a tours', assertFails(put(real,'tours/x.pdf','application/pdf')));
await t('banner video OK', assertSucceeds(put(real,'banners/v.mp4','video/mp4')));
await t('push imagen >1MB rechazada', assertFails(put(real,'push/g.png','image/png',new Uint8Array(1100000))));
await t('agencia sube beneficio a SU carpeta', assertSucceeds(put(real,'solicitudes_beneficios/uidReal/beneficio-0.jpg','image/jpeg')));
await t('agencia NO sube a carpeta ajena', assertFails(put(real,'solicitudes_beneficios/otro/beneficio-0.jpg','image/jpeg')));
await t('lectura pública de fotos sigue OK', assertSucceeds(nadie.ref('tours/a.png').getDownloadURL()));
await t('carpeta no prevista bloqueada', assertFails(put(real,'otra/x.png','image/png')));
await t('prestador SÍ borra foto (edición de tour)', assertSucceeds(real.ref('tours/x.png').delete()));
console.log(`\n${ok} OK, ${fail} fallas`); await env.cleanup(); process.exit(fail?1:0);
